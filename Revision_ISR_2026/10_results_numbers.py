"""
10_results_numbers.py - every number the revised Results section needs that is not yet
in a verified output file, recomputed from the raw study files.

READ-ONLY with respect to the study data: it only opens files in the nlpglove folder
and writes new files into Revision_ISR_2026/outputs/.

Run on the lab PC (needs torch + transformers + scipy, like 02_paper_numbers.py):
    python 10_results_numbers.py

Writes
    outputs/results_numbers.md      all numbers, with the sentence they support
    outputs/exp2_items.csv          Experiment 2, one row per command (no model needed)
    outputs/exp3_items.csv          Experiment 3, one row per test prompt and model
    outputs/exp4_items.csv          Experiment 4, base / personalised / DeepSeek per test prompt
    outputs/exp4_cross.csv          Experiment 4, cross-participant accuracy on held-out prompts
    outputs/exp4_perclass_f1.csv    Experiment 4, per-class F1 per participant (base, personalised)
"""
from __future__ import annotations

import math
import re
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import binomtest, wilcoxon
from sklearn.metrics import f1_score, precision_recall_fscore_support

from common import (BASE_MODEL, CL_DIR, LABELS, OUT, PAPER_IDS, PARTICIPANTS, ROOT,
                    STUDY_DIR, USER_STUDY_DIR, load_participant, load_xlsx_prompts,
                    norm_label, wilson)

LINES: list[str] = []


def p(s=""):
    print(s)
    LINES.append(s)


def mcnemar_exact(a_only: int, b_only: int) -> float:
    """Exact two-sided McNemar test on the discordant pairs."""
    n = a_only + b_only
    return 1.0 if n == 0 else binomtest(a_only, n, 0.5).pvalue


def fmt_ci(k, n):
    lo, hi = wilson(k, n)
    return f"{k / n:.3f} [{lo:.3f}, {hi:.3f}]"


def norm_text(t):
    return re.sub(r"[^a-z0-9 ]", "", str(t).lower()).strip()


# =========================================================================== Exp 2
p("# Results numbers (auto-generated by 10_results_numbers.py)\n")
p("## Experiment 2 - live speech, 20 participants x 10 commands, both models\n")

rows = []
for u in range(1, 21):
    b = pd.read_csv(USER_STUDY_DIR / f"bert_results_user{u}.csv")
    d = pd.read_csv(USER_STUDY_DIR / f"deepseek_results_user{u}.csv")
    for i in range(min(len(b), len(d))):
        rb, rd = b.iloc[i], d.iloc[i]
        def gold(r):
            # same rule as the original analysis scripts (all_vizualizations.py)
            if pd.notnull(r["correction"]) and str(r["correction"]).strip() != "":
                return norm_label(r["correction"])
            if str(r["feedback"]).strip().lower() == "yes":
                return norm_label(r["prediction"])
            return None
        rows.append({
            "user": u, "scenario": i + 1, "prompt": str(rb["prompt"]).strip(),
            "chars": len(str(rb["prompt"]).strip()),
            "words": len(str(rb["prompt"]).split()),
            "bert_pred": norm_label(rb["prediction"]), "bert_yes": str(rb["feedback"]).strip().lower() == "yes",
            "bert_gold": gold(rb),
            "ds_pred": norm_label(rd["prediction"]), "ds_yes": str(rd["feedback"]).strip().lower() == "yes",
            "ds_gold": gold(rd),
        })
E2 = pd.DataFrame(rows)
E2.to_csv(OUT / "exp2_items.csv", index=False)
n = len(E2)
kb, kd = int(E2.bert_yes.sum()), int(E2.ds_yes.sum())
p(f"- Commands: {n} per model")
p(f"- UCIM DistilBERT: {fmt_ci(kb, n)}  ({kb}/{n})")
p(f"- UCIM DeepSeek:   {fmt_ci(kd, n)}  ({kd}/{n})")
both = int((E2.bert_yes & E2.ds_yes).sum()); neither = int((~E2.bert_yes & ~E2.ds_yes).sum())
b_only = int((E2.bert_yes & ~E2.ds_yes).sum()); d_only = int((~E2.bert_yes & E2.ds_yes).sum())
p(f"- Paired: both confirmed {both}, only DeepSeek {d_only}, only DistilBERT {b_only}, neither {neither}")
p(f"- Exact McNemar (command level): p = {mcnemar_exact(b_only, d_only):.2g}")

pu = E2.groupby("user")[["bert_yes", "ds_yes"]].mean()
q = lambda s: f"median {s.median():.2f}, IQR [{s.quantile(.25):.2f}, {s.quantile(.75):.2f}], range {s.min():.2f}-{s.max():.2f}"
p(f"- Per participant DistilBERT: {q(pu.bert_yes)}")
p(f"- Per participant DeepSeek:   {q(pu.ds_yes)}")
higher = int((pu.ds_yes > pu.bert_yes).sum()); tie = int((pu.ds_yes == pu.bert_yes).sum())
p(f"- Preference (higher UCIM): DeepSeek {higher}/20, tie {tie}/20, DistilBERT {20 - higher - tie}/20")
w = wilcoxon(pu.ds_yes, pu.bert_yes)
p(f"- Wilcoxon signed-rank on per-participant UCIM: W = {w.statistic:.1f}, p = {w.pvalue:.2g}")

for tag, col_p, col_g in (("DistilBERT", "bert_pred", "bert_gold"), ("DeepSeek", "ds_pred", "ds_gold")):
    sub = E2[E2[col_g].notna()]
    acc = (sub[col_p] == sub[col_g]).mean()
    pr, rc, f1, sup = precision_recall_fscore_support(sub[col_g], sub[col_p], labels=LABELS, zero_division=0)
    p(f"\n{tag}: accuracy against its own gold labels (as in the original figures) = {acc:.3f} (n = {len(sub)})")
    p("| class | precision | recall | F1 | n |\n|---|---|---|---|---|")
    for l, a, b_, c, s in zip(LABELS, pr, rc, f1, sup):
        p(f"| {l} | {a:.2f} | {b_:.2f} | {c:.2f} | {s} |")

# length effect, binned (all commands, no length filter)
p("\nAccuracy by command length (characters, quartile bins over all 200 commands):")
E2["len_bin"] = pd.qcut(E2.chars, 4, duplicates="drop")
p("| length (chars) | n | DistilBERT | DeepSeek |\n|---|---|---|---|")
for b_, g in E2.groupby("len_bin", observed=True):
    gb = g[g.bert_gold.notna()]; gd = g[g.ds_gold.notna()]
    p(f"| {b_} | {len(g)} | {(gb.bert_pred == gb.bert_gold).mean():.2f} | {(gd.ds_pred == gd.ds_gold).mean():.2f} |")

# =========================================================================== Exp 3
p("\n## Experiment 3 - task specialisation (kitchen), single run\n")
import torch  # noqa: E402  (only needed from here on)
from cl_core import load_base, predict  # noqa: E402

EXP3_MODEL = ROOT / "Continual_Learning_Experiments" / "Tester-21" / "adaptive_model"
log21 = pd.read_csv(EXP3_MODEL.parent / "log.csv", encoding="cp1252")
train_nn = load_xlsx_prompts(CL_DIR / "Kitchen_train_nonnative.xlsx")
same = [norm_text(a) == norm_text(b) for a, b in zip(log21.input_text, train_nn.prompt)]
p(f"- Check: Tester-21 adapted on Kitchen_train_nonnative.xlsx in the same order: {all(same) and len(same) == len(train_nn)} "
  f"({sum(same)}/{len(train_nn)} prompts match); model updates in log: {log21.update_number.notna().sum()}")

tok_b, base_m = load_base(BASE_MODEL)
tok_a, ad_m = load_base(EXP3_MODEL)
e3 = []
for fname in ["kitchen_test_nonnative.xlsx", "repair_test_nonnative.xlsx", "kitchen_test.xlsx", "repair_test.xlsx"]:
    T = load_xlsx_prompts(CL_DIR / fname)
    ib, _ = predict(base_m, tok_b, list(T.prompt))
    ia, _ = predict(ad_m, tok_a, list(T.prompt))
    ok_b = np.array([LABELS[i] == l for i, l in zip(ib, T.label)])
    ok_a = np.array([LABELS[i] == l for i, l in zip(ia, T.label)])
    for j in range(len(T)):
        e3.append({"set": fname, "prompt": T.prompt[j], "label": T.label[j],
                   "base_pred": LABELS[ib[j]], "adapted_pred": LABELS[ia[j]]})
    nn = len(T)
    p(f"- {fname} (n = {nn}): base {fmt_ci(int(ok_b.sum()), nn)} -> adapted {fmt_ci(int(ok_a.sum()), nn)}; "
      f"gain {100 * (ok_a.mean() - ok_b.mean()):+.1f} pp; only base correct {int((ok_b & ~ok_a).sum())}, "
      f"only adapted correct {int((ok_a & ~ok_b).sum())}; exact McNemar p = "
      f"{mcnemar_exact(int((ok_b & ~ok_a).sum()), int((ok_a & ~ok_b).sum())):.3g}")
pd.DataFrame(e3).to_csv(OUT / "exp3_items.csv", index=False)
p("(The paper's Experiment 3 numbers should match the two *_nonnative rows; the other two rows are for reference.)")

# =========================================================================== Exp 4
p("\n## Experiment 4 - personalisation, 4 participants, 70 held-out prompts each\n")
ds = pd.read_csv(OUT / "llm_baseline_deepseek_deepseek-reasoner.csv")
items, f1rows, summ = [], [], []
test_sets = {}
for u in PARTICIPANTS:
    df = load_participant(u)
    test = df.iloc[140:].reset_index(drop=True)
    test_sets[u] = test
    run = sorted((STUDY_DIR / "experiment_results" / u).glob("*/results_test_phase.csv"))[-1]
    R = pd.read_csv(run)
    assert [norm_text(a) for a in R.prompt] == [norm_text(b) for b in test.prompt], f"{u}: test prompts differ"
    pers = [norm_label(x) for x in R.pred_label]
    ib, _ = predict(base_m, tok_b, list(test.prompt))
    base = [LABELS[i] for i in ib]
    dsu = ds[ds.group == u].reset_index(drop=True)
    assert [norm_text(a) for a in dsu.prompt] == [norm_text(b) for b in test.prompt], f"{u}: DeepSeek prompts differ"
    dsp = [norm_label(x) for x in dsu.pred]
    ok_b = np.array([a == l for a, l in zip(base, test.label)])
    ok_p = np.array([a == l for a, l in zip(pers, test.label)])
    ok_d = np.array([a == l for a, l in zip(dsp, test.label)])
    # does the saved adaptive model reproduce the logged personalised predictions?
    am = ROOT / "Continual_Learning_Experiments" / u / "adaptive_model"
    tok_u, mod_u = load_base(am)
    iu, _ = predict(mod_u, tok_u, list(test.prompt))
    reproduces = float(np.mean([LABELS[i] == a for i, a in zip(iu, pers)]))
    for j in range(len(test)):
        items.append({"participant": PAPER_IDS[u], "prompt": test.prompt[j], "label": test.label[j],
                      "base_pred": base[j], "pers_pred": pers[j], "deepseek_pred": dsp[j]})
    fb = f1_score(test.label, base, labels=LABELS, average=None, zero_division=0)
    fp = f1_score(test.label, pers, labels=LABELS, average=None, zero_division=0)
    for l, a, b_ in zip(LABELS, fb, fp):
        f1rows.append({"participant": PAPER_IDS[u], "label": l, "f1_base": a, "f1_pers": b_})
    bo, po = int((ok_b & ~ok_p).sum()), int((ok_p & ~ok_b).sum())
    summ.append({"participant": PAPER_IDS[u], "base": ok_b.mean(), "pers": ok_p.mean(), "deepseek": ok_d.mean(),
                 "gain_pp": 100 * (ok_p.mean() - ok_b.mean()), "only_base": bo, "only_pers": po,
                 "mcnemar_p": mcnemar_exact(bo, po), "saved_model_reproduces": reproduces})
S = pd.DataFrame(summ)
S.to_csv(OUT / "exp4_summary.csv", index=False)
pd.DataFrame(items).to_csv(OUT / "exp4_items.csv", index=False)
pd.DataFrame(f1rows).to_csv(OUT / "exp4_perclass_f1.csv", index=False)
p("| participant | base | personalised | gain (pp) | only base right | only pers. right | exact McNemar p | DeepSeek | saved model reproduces log |")
p("|---|---|---|---|---|---|---|---|---|")
for r in S.itertuples():
    p(f"| {r.participant} | {r.base:.3f} | {r.pers:.3f} | {r.gain_pp:+.1f} | {r.only_base} | {r.only_pers} | "
      f"{r.mcnemar_p:.3g} | {r.deepseek:.3f} | {r.saved_model_reproduces:.2f} |")
p(f"| mean | {S.base.mean():.3f} | {S.pers.mean():.3f} | {S.gain_pp.mean():+.1f} | | | | {S.deepseek.mean():.3f} | |")
p(f"| SD | {S.base.std(ddof=1):.3f} | {S.pers.std(ddof=1):.3f} | {S.gain_pp.std(ddof=1):.1f} | | | | {S.deepseek.std(ddof=1):.3f} | |")
bo, po = int(S.only_base.sum()), int(S.only_pers.sum())
p(f"\nPooled over the 280 test prompts: only base right {bo}, only personalised right {po}, exact McNemar p = {mcnemar_exact(bo, po):.2g}")
p("NOTE: 'saved model reproduces log' must be 1.00 for every participant; otherwise the cross-participant matrix "
  "below was not computed with the models that produced the Table 2 results.")

F = pd.DataFrame(f1rows).groupby("label")[["f1_base", "f1_pers"]].agg(["mean", "std"])
p("\nPer-class F1, mean (SD) over the four participants, base -> personalised:")
for l in LABELS:
    p(f"- {l}: {F.loc[l, ('f1_base', 'mean')]:.2f} ({F.loc[l, ('f1_base', 'std')]:.2f}) -> "
      f"{F.loc[l, ('f1_pers', 'mean')]:.2f} ({F.loc[l, ('f1_pers', 'std')]:.2f})")

I = pd.DataFrame(items)
cm = pd.crosstab(pd.Categorical(I.label, LABELS), pd.Categorical(I.pers_pred, LABELS), dropna=False)
off = [(cm.index[i], cm.columns[j], int(cm.iat[i, j])) for i in range(7) for j in range(7) if i != j]
off.sort(key=lambda x: -x[2])
p("\nLargest confusions of the personalised models (true -> predicted, count of 40): " +
  "; ".join(f"{a} -> {b}: {c}" for a, b, c in off[:5]))

# cross-participant accuracy on the HELD-OUT prompts only
cross = []
for u in PARTICIPANTS:
    tok_u, mod_u = load_base(ROOT / "Continual_Learning_Experiments" / u / "adaptive_model")
    for v in PARTICIPANTS:
        T = test_sets[v]
        iv, _ = predict(mod_u, tok_u, list(T.prompt))
        cross.append({"model_of": PAPER_IDS[u], "tested_on": PAPER_IDS[v],
                      "acc": float(np.mean([LABELS[i] == l for i, l in zip(iv, T.label)]))})
C = pd.DataFrame(cross).pivot(index="model_of", columns="tested_on", values="acc")
C.to_csv(OUT / "exp4_cross.csv")
base_acc = dict(zip(S.participant, S.base))
own = np.mean([C.loc[k, k] - base_acc[k] for k in C.index])
other = [C.loc[a, b] - base_acc[b] for a in C.index for b in C.columns if a != b]
p("\nCross-participant accuracy (rows = model personalised to, columns = held-out prompts of):")
p("```\n" + C.round(3).to_string() + "\n```")
p(f"\nChange vs base model: own participant {100 * own:+.1f} pp (mean); other participants "
  f"{100 * np.mean(other):+.1f} pp (mean, range {100 * min(other):+.1f} to {100 * max(other):+.1f})")

(OUT / "results_numbers.md").write_text("\n".join(LINES), encoding="utf-8")
print(f"\nwritten: {OUT / 'results_numbers.md'}")
