# Voice-to-Grasp - revision analyses (see README.md, section "Reproducing the paper's numbers").
# All scripts in Revision_ISR_2026 read the data folders of this repository (read-only) and write
# only to Revision_ISR_2026/outputs/. Paths are set in common.py.

"""
02_paper_numbers.py - recompute every number the reviewers can check, from the
ORIGINAL result files (read-only), so the revised text/tables are consistent.

  A. Experiment 1 - accuracy of the 6 models on the 96 prompts (paper rule:
     correct if prediction is any of the 4 assessors' labels), Wilson 95% CI,
     parse failures, exact McNemar DistilBERT vs DeepSeek, and DistilBERT /
     RoBERTa accuracy after removing the near-duplicate prompts (leakage check).
  B. Experiment 4 - Table 2 rebuilt: base accuracy (re-computed with the base
     checkpoint), personalised accuracy + #updates (from the original
     experiment_summary.json files), gain, Wilson CI, mean/SD, exact Spearman
     rho with an exact permutation p-value (n=4 has only 24 orderings).

Writes outputs/paper_numbers.md and outputs/table2_recomputed.csv

Run: python 02_paper_numbers.py
"""
from __future__ import annotations

import csv
import difflib
import itertools
import json
from math import comb

import numpy as np
import pandas as pd

from cl_core import load_base, predict
from common import (BASE_MODEL, LABELS, OUT, PAPER_IDS, PARTICIPANTS, ROOT,
                    STUDY_DIR, load_base_dataset, load_exp1, load_participant,
                    norm_label, norm_text, wilson)

L = []


def p(s=""):
    print(s)
    L.append(s)


def mcnemar_exact(a_ok, b_ok):
    a_ok, b_ok = np.asarray(a_ok, bool), np.asarray(b_ok, bool)
    b = int((a_ok & ~b_ok).sum())
    c = int((~a_ok & b_ok).sum())
    n = b + c
    if n == 0:
        return b, c, 1.0
    k = min(b, c)
    pval = min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n)
    return b, c, pval


# ======================================================================= A
p("# Recomputed numbers (auto-generated by 02_paper_numbers.py)\n")
p("## A. Experiment 1 (96 prompts, 4 assessors)")
ex1 = load_exp1()
truth = dict(zip(ex1.prompt, ex1.labels))
PRED = {
    "DistilBERT (fine-tuned)": ROOT / "All_predictions" / "prediction_bert_updated.csv",
    "RoBERTa (fine-tuned)": ROOT / "All_predictions" / "Experiment1" / "prediction_roberta_updated.csv",
    "DeepSeek (zero-shot)": ROOT / "All_predictions" / "Experiment1" / "prediction_deepseek.csv",
    "ChatGPT-5 (zero-shot)": ROOT / "All_predictions" / "Experiment1" / "prediction_chatGPT5.csv",
    "Mistral-7B (zero-shot)": ROOT / "All_predictions" / "Experiment1" / "prediction_mistral.csv",
    "Llama-2-7B (zero-shot)": ROOT / "All_predictions" / "Experiment1" / "prediction_llama2.csv",
}
ok = {}
p("| Model | Accuracy | 95% Wilson CI | parse failures |\n|---|---|---|---|")
for name, f in PRED.items():
    if not f.exists():
        p(f"| {name} | (file missing) | | |")
        continue
    rows = [r for r in csv.reader(open(f, encoding="utf-8-sig")) if r and r[0].strip() in truth]
    pm = {r[0].strip(): (r[1].strip() if len(r) > 1 else "") for r in rows}   # align BY PROMPT
    fails = sum(1 for p_ in ex1.prompt if norm_label(pm.get(p_)) is None)
    ok[name] = np.array([norm_label(pm.get(p_)) in truth[p_] for p_ in ex1.prompt])
    k = int(ok[name].sum())
    lo, hi = wilson(k, len(ex1))
    p(f"| {name} | {k/len(ex1):.3f} ({k}/96) | [{lo:.2f}, {hi:.2f}] | {fails} |")
p("\nNOTE: prediction_llama2.csv has a header row. Scripts/accuracy.py compares by row index, so with the "
  "header the Llama-2 predictions are shifted by one line (by-index accuracy ~0.10 vs the aligned value in the table). "
  "Use the aligned value and report the parse failures (outputs that were not one of the 7 labels).")
if "DistilBERT (fine-tuned)" in ok and "DeepSeek (zero-shot)" in ok:
    b, c, pv = mcnemar_exact(ok["DistilBERT (fine-tuned)"], ok["DeepSeek (zero-shot)"])
    p(f"\nExact McNemar DistilBERT vs DeepSeek on Exp 1: DistilBERT-only correct {b}, DeepSeek-only {c}, p={pv:.3f} "
      "-> on the 96 prompts the two are NOT significantly different; say 'comparable' rather than 'higher'.")

# leakage-filtered accuracy
base = load_base_dataset()
train_norm = list({norm_text(t) for t in base.prompt})
near = np.array([bool(difflib.get_close_matches(norm_text(t), train_norm, n=1, cutoff=0.85))
                 for t in ex1.prompt])
p(f"\nLeakage-filtered subset (drop {near.sum()} near-duplicate prompts, n={(~near).sum()}):")
for name in ok:
    p(f"- {name}: {ok[name][~near].mean():.3f} (all 96: {ok[name].mean():.3f})")

# base checkpoint used in Exp 2-4 on Exp 1
tok, mdl = load_base(BASE_MODEL)
ids, _ = predict(mdl, tok, list(ex1.prompt))
bacc = np.mean([LABELS[i] in s for i, s in zip(ids, ex1.labels)])
p(f"\nCheck: bert_finetuned_updated (the checkpoint used in Exp 2-4) on the 96 prompts = {bacc:.3f} "
  "(should match the DistilBERT row above; if not, state which checkpoint Exp 1 used).")

# ======================================================================= B
p("\n## B. Experiment 4 - Table 2 rebuilt")
res_dir = STUDY_DIR / "experiment_results"
rows = []
for u in PARTICIPANTS:
    runs = sorted((res_dir / u).glob("*/experiment_summary.json")) if (res_dir / u).exists() else []
    if not runs:
        print(f"[warn] no experiment_summary.json for {u}")
        continue
    s = json.loads(runs[-1].read_text(encoding="utf-8"))
    df = load_participant(u)
    test = df.iloc[140:]
    ids, _ = predict(mdl, tok, list(test.prompt))
    base_acc = float(np.mean([LABELS[i] == l for i, l in zip(ids, test.label)]))
    pers = s["test_phase"]["accuracy"]
    k = s["test_phase"]["correct"]
    n = s["test_phase"]["samples"] if isinstance(s["test_phase"]["samples"], int) else len(s["test_phase"]["samples"])
    lo, hi = wilson(k, n)
    blo, bhi = wilson(int(round(base_acc * n)), n)
    rows.append({"participant": PAPER_IDS[u], "name": u, "base_acc": base_acc,
                 "base_ci": f"[{blo:.3f}, {bhi:.3f}]",
                 "personalised_acc": pers, "pers_ci": f"[{lo:.3f}, {hi:.3f}]",
                 "gain_pp": 100 * (pers - base_acc),
                 "updates": s["training_phase"]["model_updates"],
                 "adapt_phase_online_acc": s["training_phase"]["accuracy"]})
T = pd.DataFrame(rows)
T.to_csv(OUT / "table2_recomputed.csv", index=False)


def summarise(T, label):
    p(f"\n### {label}")
    p("| Participant | Base acc | Personalised acc [95% Wilson] | Gain (pp) | Model updates |\n|---|---|---|---|---|")
    for _, r in T.iterrows():
        p(f"| {r.participant} | {r.base_acc:.3f} | {r.personalised_acc:.3f} {r.pers_ci} | {r.gain_pp:+.1f} | {r.updates} |")
    p(f"| **Mean** | {T.base_acc.mean():.3f} | {T.personalised_acc.mean():.3f} | {T.gain_pp.mean():+.1f} | {T.updates.mean():.1f} |")
    p(f"| **SD** | {T.base_acc.std(ddof=1):.3f} | {T.personalised_acc.std(ddof=1):.3f} | {T.gain_pp.std(ddof=1):.1f} | {T.updates.std(ddof=1):.1f} |")
    # Spearman + exact permutation test
    x, y = T.updates.values, T.gain_pp.values
    rx, ry = pd.Series(x).rank().values, pd.Series(y).rank().values
    rho = float(np.corrcoef(rx, ry)[0, 1])
    perms = [float(np.corrcoef(rx, pd.Series(np.array(pp)).rank().values)[0, 1])
             for pp in itertools.permutations(y)]
    p_two = np.mean([abs(r) >= abs(rho) - 1e-12 for r in perms])
    p(f"\nSpearman rho(updates, gain) = {rho:.2f}; exact permutation p (two-sided) = {p_two:.3f} "
      f"over {len(perms)} orderings (minimum attainable two-sided p with n={len(T)} = {2/len(perms):.3f}). "
      "The paper's rho=0.90, p=0.037 is not reproduced by the original result files - report the value above "
      "as a descriptive trend only, or drop the claim.")
    # exact sign / permutation test on gains
    signs = list(itertools.product([-1, 1], repeat=len(T)))
    obs = T.gain_pp.mean()
    p_sign = np.mean([np.mean(np.array(s_) * np.abs(T.gain_pp.values)) >= obs - 1e-12 for s_ in signs])
    p(f"Exact sign-flip permutation test that mean gain > 0: p (one-sided) = {p_sign:.3f} "
      f"({2**len(T)} sign patterns; minimum possible = {1/2**len(T):.3f}).")
    p("Item-level paired evidence (McNemar, base vs personalised on the same 70 test prompts) is produced by "
      "03_cl_ablations.py reproductions - use those for per-participant significance.")


if len(T):
    summarise(T, "Experiment 4 (the 4 participants in the paper)")
    p("\nPaper text to correct: Table 2 mean/SD rows; 'mean gain of 15.75 pp' vs base 0.59 -> 0.67; "
      "'up to 20.7 pp' (that is a CI bound); 'participant 5' (-> P1); 'remaining four' (-> other three); "
      "Spearman p=0.037 (not attainable with n=4).")

(OUT / "paper_numbers.md").write_text("\n".join(L), encoding="utf-8")
print(f"\n-> {OUT / 'paper_numbers.md'}")
