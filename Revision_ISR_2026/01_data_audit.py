# Voice-to-Grasp - revision analyses (see README.md, section "Reproducing the paper's numbers").
# All scripts in Revision_ISR_2026 read the data folders of this repository (read-only) and write
# only to Revision_ISR_2026/outputs/. Paths are set in common.py.

"""
01_data_audit.py - answers the "is the data sound?" questions (R3 #4, R2 #2/#8,
R3 #6) without training anything.

Produces outputs/data_audit.md with:
  1. Size + class balance of the DistilBERT fine-tuning set (paper says 1,906)
  2. Train/test leakage: exact and near-duplicate overlap between the 96
     Experiment-1 test prompts and the fine-tuning set
  3. Experiment-2 metrics, cleanly separated:
       - user-confirmed intent match per model (the yes/no measure)
       - per-user rate distribution, median, IQR
       - "preference" = #users for whom DeepSeek > DistilBERT, ties, etc.
       - paired Wilcoxon signed-rank test across the 20 users
  4. Experiment-2 transcripts: length stats + examples of likely ASR errors
  5. Experiment-4 study sheets: class balance per participant

Run:  python 01_data_audit.py
"""
from __future__ import annotations

import difflib
from collections import Counter

import numpy as np
import pandas as pd

from common import (OUT, PARTICIPANTS, load_base_dataset, load_exp1, load_exp2,
                    load_participant, norm_text)

lines = []


def p(s=""):
    print(s)
    lines.append(s)


# ---------------------------------------------------------------- 1. dataset
base = load_base_dataset()
p("# Data audit (auto-generated by 01_data_audit.py)\n")
p("## 1. DistilBERT fine-tuning set")
import json as _j
from common import DATASET_FILES
for f in DATASET_FILES:
    if f.exists():
        txt = f.read_text(encoding="utf-8")
        try:
            raw = _j.loads(txt)
        except _j.JSONDecodeError:
            raw = [_j.loads(l) for l in txt.splitlines() if l.strip()]
        p(f"- {f.name}: {len(raw)} raw entries")
p(f"- **combined unique: {len(base)}** (paper states 1,906 - reconcile)")
p("- class counts: " + ", ".join(f"{k} {v}" for k, v in Counter(base.label).most_common()))

# ---------------------------------------------------------------- 2. leakage
ex1 = load_exp1()
train_norm = list({norm_text(t) for t in base.prompt})
train_set = set(train_norm)
exact, near = [], []
for t in ex1.prompt:
    nt = norm_text(t)
    if nt in train_set:
        exact.append(t)
        continue
    m = difflib.get_close_matches(nt, train_norm, n=1, cutoff=0.85)
    if m:
        near.append((t, m[0], difflib.SequenceMatcher(None, nt, m[0]).ratio()))
p("\n## 2. Leakage between Experiment-1 test prompts (n=%d) and the fine-tuning set" % len(ex1))
p(f"- exact duplicates (after lower-casing, punctuation removed): **{len(exact)}**")
p(f"- near duplicates (difflib ratio >= 0.85): **{len(near)}** ({100*len(near)/len(ex1):.1f}%)")
for a, b, r in sorted(near, key=lambda x: -x[2]):
    p(f"  - `{a}`  ~  `{b}`  ({r:.2f})")
p("- Suggested text: *No Experiment-1 test prompt appears verbatim in the fine-tuning data; "
  f"{len(near)} of {len(ex1)} are close paraphrases of a training prompt (similarity >= 0.85). "
  "Removing them changes DistilBERT accuracy from X to Y (see 02_paper_numbers.py).*")
pd.DataFrame(near, columns=["exp1_prompt", "closest_train_prompt", "ratio"]).to_csv(
    OUT / "leakage_near_duplicates.csv", index=False)

# ---------------------------------------------------------------- 3. Exp 2
e2 = load_exp2()
p("\n## 3. Experiment 2 - metrics kept apart (20 users x 10 spoken commands)")
p("Definitions to use in the paper:")
p("- **User-confirmed intent match (UCIM)**: fraction of commands for which the participant answered 'yes' "
  "to 'did the glove do what you intended?'. This is what Fig. 3b/3d currently call accuracy / task completion.")
p("- **Classification accuracy vs. reference label**: prediction in the accepted-label set (user-confirmed "
  "prediction of either model, or the user's correction). Close to UCIM by construction - say so.")
p("- **Physical task success**: NOT measured in this study (participants did the reaching; no object-level "
  "success criterion was recorded). Do not claim it.")
p("- **Preference**: per participant, which model had the higher UCIM.\n")
per_user = e2.groupby("user").agg(bert=("bert_ok", "mean"), deepseek=("deepseek_ok", "mean"))
for m in ("bert", "deepseek"):
    v = per_user[m]
    pooled = e2[f"{m}_ok"].mean()
    p(f"- {m}: pooled UCIM {pooled:.3f} ({e2[f'{m}_ok'].sum()}/{len(e2)}); per-user median {v.median():.2f}, "
      f"IQR [{v.quantile(.25):.2f}, {v.quantile(.75):.2f}], min {v.min():.2f}, max {v.max():.2f}")
better = (per_user.deepseek > per_user.bert).sum()
tie = (per_user.deepseek == per_user.bert).sum()
worse = (per_user.deepseek < per_user.bert).sum()
p(f"- DeepSeek higher for **{better}/20** users, tie {tie}, lower {worse}  "
  f"(the paper's '90% of users' = {better}/20 = {better/20:.0%} - check against Fig. 3d)")
try:
    from scipy.stats import wilcoxon
    w = wilcoxon(per_user.deepseek, per_user.bert, zero_method="wilcox")
    p(f"- Paired Wilcoxon signed-rank (per-user UCIM, n=20): W={w.statistic:.1f}, p={w.pvalue:.4g} "
      "-> this is the test that can justify the word 'significantly' in Sec. 2.2.2")
except Exception as ex:  # scipy missing
    p(f"- (scipy not available for Wilcoxon: {ex})")
# accuracy against accepted set
acc_b = np.mean([bp in L for bp, L in zip(e2.bert_pred, e2.labels)])
acc_d = np.mean([dp in L for dp, L in zip(e2.deepseek_pred, e2.labels)])
p(f"- Accuracy vs accepted-label set: DistilBERT {acc_b:.3f}, DeepSeek {acc_d:.3f}")
both_ok = (e2.bert_ok & e2.deepseek_ok).mean()
p(f"- Both models accepted on the same command: {both_ok:.3f}; neither accepted: "
  f"{(~e2.bert_ok & ~e2.deepseek_ok).mean():.3f}")
per_user.to_csv(OUT / "exp2_per_user_ucim.csv")

# per scenario
p("\nPer-scenario UCIM (scenario numbers as in the paper's list):")
sc = e2.groupby("scenario").agg(bert=("bert_ok", "mean"), deepseek=("deepseek_ok", "mean"))
p("| scenario | DistilBERT | DeepSeek |\n|---|---|---|")
for s, r in sc.iterrows():
    p(f"| {s} | {r.bert:.2f} | {r.deepseek:.2f} |")

# ---------------------------------------------------------------- 4. transcripts
lens = e2.prompt.str.split().str.len()
p("\n## 4. Experiment-2 transcripts (Whisper 'base', participant-confirmed)")
p(f"- words per command: median {lens.median():.0f}, IQR [{lens.quantile(.25):.0f}, {lens.quantile(.75):.0f}], "
  f"max {lens.max()}")
asr_hints = e2[e2.prompt.str.contains(r"razor|\.\.\.|\(couldn|Whisper error", regex=True)]
p(f"- transcripts with visible ASR artefacts / disfluency (heuristic): {len(asr_hints)}")
for t in asr_hints.prompt.head(8):
    p(f"  - `{t}`")
p("- NOTE: participants confirmed the transcript before it was sent to the models, so ASR errors that changed "
  "the meaning were (presumably) re-recorded. Say this explicitly and report how often a re-recording happened "
  "if you remember / can reconstruct it.")

# ---------------------------------------------------------------- 5. Exp 4 sheets
p("\n## 5. Experiment-4 study sheets")
for u in PARTICIPANTS:
    d = load_participant(u)
    a, t = d.iloc[:140], d.iloc[140:]
    p(f"- {u}: {len(d)} prompts; adaptation per class {dict(Counter(a.label))}; test per class {dict(Counter(t.label))}")

(OUT / "data_audit.md").write_text("\n".join(lines), encoding="utf-8")
print(f"\n-> {OUT / 'data_audit.md'}")
